import { competition, formatKoreanDateRange } from "@/config/competition";
import { container } from "@/lib/layout";
import { ApplyDdayBadge } from "@/components/ApplyDdayBadge";

/* ============================================================================
 *  '참가 신청'(/apply) 화면의 머리띠 — **이 화면 전용입니다**
 *
 *  ★★★ 왜 공용 PageHeader 를 쓰지 않나 (2026-08-19 담당자 요청) ★★★
 *
 *   다른 일곱 화면의 머리띠는 src/components/PageHeader.tsx 그대로입니다.
 *   이 화면만 따로 만든 이유는 두 가지입니다.
 *
 *   1) 여기는 '둘러보는 화면'이 아니라 **신청서를 쓰러 오는 화면**입니다.
 *      큰 사진 머리띠가 정작 해야 할 일('신청 전 확인해 주세요' 상자)을
 *      화면 아래로 밀어냈습니다. 그래서 배경을 남색 단색으로 바꾸고 높이를
 *      3분의 1 수준으로 줄였습니다.
 *      ℹ️ 배경 사진(phoneShot, 휴대폰으로 시상식을 찍는 모습)은 글자가
 *         놓이는 자리에 인물과 트로피가 겹쳐, 막을 어떻게 씌워도 읽기가
 *         편해지지 않았습니다. 사진과 config 항목을 함께 지웠습니다.
 *   2) 내용의 모양이 다릅니다. 다른 화면은 '제목 + 설명 한 줄'인데, 여기는
 *      '제목 + (D-day 배지 · 접수 기간)' 두 덩어리가 가로로 놓입니다.
 *
 *   ⚠️ 이 파일을 PageHeader 로 되돌려 합치지 마세요. 합치려면 공용
 *      컴포넌트에 '이 화면만' 갈래를 또 만들어야 하고, 그 갈래를 잘못
 *      건드리면 나머지 일곱 화면이 함께 바뀝니다. 이 화면만 다르게 두는
 *      값이 그 위험보다 쌉니다.
 *
 *  ★ 남색은 종목 상세 화면 머리띠와 **같은 색**입니다 (bg-brand-700) ★
 *    새 색을 만들지 않았습니다. 종목 상세는 <PageHeader solid /> 로 같은
 *    색을 씁니다. 색을 바꿔야 하면 globals.css 의 --color-brand-700 한
 *    곳만 고치면 둘이 함께 바뀝니다.
 *
 *  ⚠️⚠️ 여기에 '신청 폼 바로가기' 같은 단추를 만들지 마세요 ⚠️⚠️
 *     (2026-08-19 담당자 지시) 아래 '신청 전 확인해 주세요' 상자를 읽지 않고
 *     건너뛰는 지름길이 되기 때문입니다. 그 상자에는 개인정보 국외이전
 *     안내가 들어 있어, 신청자가 폼보다 먼저 읽어야 합니다
 *     (CLAUDE.md 의 개인정보 절). 신청 단추는 그 상자 안 맨 아래에만 둡니다.
 *
 *  ★ 글자는 여기에 적지 않습니다 ★
 *    접수 기간은 config 의 registration.opensAt / closesAt 에서 옵니다.
 *    D-day 문구도 config 의 countdown 에서 옵니다.
 *    이 파일에 직접 적힌 글자는 제목 '참가 신청' 한 줄뿐입니다.
 * ========================================================================== */

export function ApplyHero() {
  const { registration } = competition;

  return (
    /* 가운데 정렬된 좁은 칸(container)은 다른 머리띠와 같습니다 —
       그래서 제목의 왼쪽 끝이 아래 상자의 왼쪽 끝과 한 줄로 맞습니다. */
    <section className="bg-brand-700 text-white">
      <div className={container}>
        {/* ★★★ 띠 높이 ★★★
              여백을 사진 머리띠의 **약 4분의 1** 로 줄였습니다.
                바꾸기 전 (사진)  py-22 / sm:py-28 / lg:py-36  (88 / 112 / 144px)
                바꾼 뒤 (단색)    py-4  / sm:py-5  / lg:py-6   (16 /  20 /  24px)
              띠 전체 높이는 (글자 크기·줄 간격까지 더해서) 이렇게 됩니다.
                넓은 화면(1024px+)  380px → 140px  (37%)
                태블릿(640px+)      308px → 124px  (40%)
                휴대폰               252px → 139px  (55%)

              ★ 이 값을 정한 기준 ★
                넓은 화면 첫 화면에서 **'신청 전 확인해 주세요' 상자의
                윗부분이 함께 보여야** 합니다. 지금은 상단 메뉴 + 맨 위 띠 +
                이 머리띠 + 상자 위 여백을 더한 값입니다.
                  상단 메뉴 80 + 맨 위 띠 36 + 머리띠 140 + 여백 64 = 320px
                이 값이 첫 화면(보통 700~900px)의 절반이 안 되므로 상자
                제목까지 넉넉히 들어옵니다.
                (80·36 은 globals.css 의 --nav-h · --dday-h 값입니다)
              ⚠️ 여백을 다시 키우려면 좁은 화면(320×568)에서 그 상자가
                 첫 화면에 남아 있는지 꼭 확인하세요.

              ℹ️ 휴대폰이 3분의 1까지 줄지 않는 것은 여백 때문이 아닙니다.
                 좁은 화면에서는 배지와 접수 기간이 두 줄로 쌓이기 때문에
                 안에 든 내용 자체가 그만큼 높습니다. 높이는 고정값이 아니라
                 내용이 정합니다 (PageHeader 와 같은 방식). */}
        <div className="py-4 sm:py-5 lg:py-6">
          {/* ⚠️ 제목은 다른 머리띠와 같은 크기입니다. 줄이지 마세요 —
                 여기가 어느 화면인지 알려 주는 유일한 글자입니다. */}
          <h1 className="text-3xl sm:text-4xl lg:text-5xl">참가 신청</h1>

          {/* ★ 좁은 화면에서는 세로로 쌓이고, 640px 이상에서 가로로 놓입니다 ★
                휴대폰에서 한 줄에 넣으면 '접수 시작까지 D-13'과 긴 날짜가
                한 줄에 들어가지 못해 배지가 눌리거나 날짜가 접힙니다.
              ℹ️ items-start → sm:items-center: 세로로 쌓일 때 배지가 왼쪽
                 끝에 붙고, 가로로 놓일 때 날짜와 가운데가 맞습니다. */}
          <div className="mt-2.5 flex flex-col items-start gap-1.5 sm:mt-4 sm:flex-row sm:items-center sm:gap-3">
            <ApplyDdayBadge />

            {/* 접수 기간 — 흰 글씨. 남색(brand-700) 위에서 대비 10:1 입니다.
                ⚠️ text-brand-100 처럼 옅은 색으로 바꾸지 마세요. 이 한 줄이
                   이 화면에서 가장 자주 확인되는 정보입니다. */}
            <p className="text-base text-white sm:text-lg">
              접수 기간{" "}
              {formatKoreanDateRange(
                registration.opensAt,
                registration.closesAt,
              )}
            </p>
          </div>
        </div>
      </div>
    </section>
  );
}
