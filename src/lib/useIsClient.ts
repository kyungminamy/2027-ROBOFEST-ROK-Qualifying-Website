"use client";

import { useSyncExternalStore } from "react";

/* ============================================================================
 *  지금 방문자의 브라우저에서 그려지는 중인지 알려 주는 도구
 *
 *  ★ 이게 왜 필요한가 (지우지 마세요) ★
 *
 *   이 사이트는 배포할 때 화면을 미리 한 번 만들어 두고 그대로 서비스합니다.
 *   그래서 '오늘'이 필요한 계산(남은 날짜, 접수 기간 판단)을 미리 만드는
 *   단계에서 해 버리면, 숫자가 '배포한 날' 기준으로 얼어붙습니다.
 *   8월에 배포하면 11월에도 계속 'D-100'이라고 표시되고,
 *   9월 1일에 접수가 시작되어도 계속 '접수 예정'이라고 표시됩니다.
 *
 *   아무도 지켜보지 않는 동안 접수를 놓치는 사고를 막기 위해,
 *   날짜 계산은 방문자의 브라우저에서 합니다.
 *   그러면 아무도 손대지 않아도 매일 정확한 숫자가 나옵니다.
 *
 *  【 사용법 】
 *    const isClient = useIsClient();
 *    미리 만드는 단계에서는 false, 방문자 브라우저에서는 true 입니다.
 *    false 인 동안 보여 줄 화면(빈 자리 또는 날짜 없는 안내)을 꼭 준비하세요.
 * ========================================================================== */

/** 외부에서 값이 바뀔 일이 없으므로 구독은 아무 일도 하지 않습니다 */
const noopSubscribe = () => () => {};

export function useIsClient(): boolean {
  return useSyncExternalStore(
    noopSubscribe,
    () => true, // 방문자 브라우저에서 그릴 때
    () => false, // 배포 시 미리 만들 때 / 첫 화면을 맞춰 그릴 때
  );
}
